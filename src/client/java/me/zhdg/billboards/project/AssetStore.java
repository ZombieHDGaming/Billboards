package me.zhdg.billboards.project;

import me.zhdg.billboards.model.BillboardProject;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.DigestInputStream;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.Locale;
import java.util.UUID;

/**
 * Copies picked files into the project's assets folder so the project doesn't depend on the original file.
 * Files are named by content hash, so importing the same file twice stores it once.
 */
public final class AssetStore {

	private AssetStore() {
	}

	/** Copies {@code source} into the replay's assets and records it in the project. Returns the asset id. */
	public static String importFile(UUID replayId, BillboardProject project, Path source) throws IOException {
		String fileName = source.getFileName().toString();
		String extension = "";
		int dot = fileName.lastIndexOf('.');
		if (dot >= 0 && dot < fileName.length() - 1) {
			extension = "." + fileName.substring(dot + 1).toLowerCase(Locale.ROOT);
		}

		String assetId = sha256(source) + extension;
		Path target = resolve(replayId, assetId);
		if (!Files.exists(target)) {
			Files.createDirectories(target.getParent());
			Path temp = target.resolveSibling(assetId + ".tmp");
			Files.copy(source, temp, StandardCopyOption.REPLACE_EXISTING);
			Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING);
		}

		project.assets.putIfAbsent(assetId, fileName);
		project.markDirty();
		return assetId;
	}

	public static Path resolve(UUID replayId, String assetId) {
		// Asset ids are generated by us, but guard against path tricks in hand-edited project files.
		if (assetId.contains("/") || assetId.contains("\\") || assetId.contains("..")) {
			throw new IllegalArgumentException("Invalid asset id: " + assetId);
		}
		return ProjectManager.assetsDirectory(replayId).resolve(assetId);
	}

	private static String sha256(Path path) throws IOException {
		try {
			MessageDigest digest = MessageDigest.getInstance("SHA-256");
			try (InputStream in = new DigestInputStream(Files.newInputStream(path), digest)) {
				in.transferTo(java.io.OutputStream.nullOutputStream());
			}
			return HexFormat.of().formatHex(digest.digest());
		} catch (NoSuchAlgorithmException e) {
			throw new IllegalStateException(e);
		}
	}
}
